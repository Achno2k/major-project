def compute_throughput_stats(channel_data, path_loss_db, Pt_watts, noise_power, bandwidth_hz):
    """
    Compute throughput statistics for a HAP

    channel_data: (n_samples, n_outputs) - channel attenuation values
    path_loss_db: path loss in dB for this HAP
    """
    # Get RF attenuation column (typically last column)
    if channel_data.ndim == 2:
        rf_attenuation_db = channel_data[:, -1]  # Last column: RF_Total_Attenuation_dB
    else:
        rf_attenuation_db = channel_data

    # Total loss = RF attenuation + path loss
    total_loss_db = rf_attenuation_db + path_loss_db

    # Convert to linear
    total_loss_linear = 10 ** (total_loss_db / 10.0)
    total_loss_linear = np.clip(total_loss_linear, 1e-12, 1e12)

    # Received power
    Pr_watts = Pt_watts / total_loss_linear

    # SNR
    snr_linear = Pr_watts / (noise_power + 1e-30)
    snr_linear = np.clip(snr_linear, 1e-12, 1e8)
    snr_db = 10 * np.log10(snr_linear)

    # Throughput (Shannon capacity)
    throughput_bps = bandwidth_hz * np.log2(1.0 + snr_linear)
    throughput_mbps = throughput_bps / 1e6

    return {
        'throughput_mbps': throughput_mbps,
        'snr_db': snr_db,
        'mean_throughput': np.mean(throughput_mbps),
        'median_throughput': np.median(throughput_mbps),
        'std_throughput': np.std(throughput_mbps),
        'mean_snr_db': np.mean(snr_db),
        'median_snr_db': np.median(snr_db),
        'total_loss_db': total_loss_db,
        'mean_loss_db': np.mean(total_loss_db)
    }

