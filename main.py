def compute_channel_matrices(channel_data, path_loss_db):
    rf_attenuation_db = channel_data[:, -1] # Last column is RF attenuation
    total_loss_db = rf_attenuation_db + path_loss_db
    total_loss_linear = 10 ** (total_loss_db / 10.0)
    # The channel gain (G) is 1/Loss_linear, normalized by noise (1/Loss * 1/N0)
    G_over_N0 = 1.0 / (np.clip(total_loss_linear, 1e-12, 1e12) * noise_power)
    return G_over_N0

# Pre-calculate the channel gain/noise ratio matrix for all HAPs
# G_over_N0_matrix shape: (N_samples_per_hap, N_HAPS)
